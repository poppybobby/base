export const MAKERS = [...new Set(CATALOG.map((l) => l.maker))]
export const VENUES = [...new Set(CATALOG.map((l) => l.venue))]
export const BODY_TYPES = [...new Set(CATALOG.map((l) => l.bodyType))]
export const SCORES = [...new Set(CATALOG.map((l) => l.score))]

export function getLot(id: string): Lot | undefined {
  return CATALOG.find((l) => l.id === id)
}

export function similarLots(lot: Lot, limit = 3): Lot[] {
  return CATALOG.filter(
    (l) =>
      l.id !== lot.id &&
      (l.bodyType === lot.bodyType || l.maker === lot.maker),
  ).slice(0, limit)
}
